/**
 * Windows MSI installs update themselves: the new .msi is downloaded and checked in the
 * background (files.ts), and on "Restart to update" a detached PowerShell helper waits
 * for Quvrelo to exit, runs `msiexec /i <file> /qb /norestart` elevated (one UAC prompt;
 * the MSI is per-machine), then reopens Quvrelo. Windows Installer is transactional: a
 * failed or cancelled upgrade leaves the installed version as it was, and the helper
 * reopens that one. The MSI's UpgradeCode (stable, from the appId) makes it a major
 * upgrade that replaces the old version.
 */
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import * as path from 'node:path';

/** PowerShell single-quoted string literal. */
export function psq(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}

export interface MsiPlan {
  pid: number;
  msi: string;
  /** Quvrelo.exe to reopen afterwards. */
  exe: string;
  log: string;
  /** msiexec's verbose log. */
  msiLog: string;
  relaunch: boolean;
  pendingDir: string;
  waitSeconds?: number;
}

/** Exit codes msiexec uses for success (3010/1641: success, reboot required/started). */
export const MSI_SUCCESS = [0, 3010, 1641];

export function msiHelperScript(p: MsiPlan): string {
  return `# Quvrelo update helper (generated by msiInstall.ts)
$ErrorActionPreference = 'Continue'
$appPid = ${Math.trunc(p.pid)}
$msi = ${psq(p.msi)}
$exe = ${psq(p.exe)}
$log = ${psq(p.log)}
$msiLog = ${psq(p.msiLog)}
$pending = ${psq(p.pendingDir)}
$relaunch = $${p.relaunch ? 'true' : 'false'}
function Log([string]$m) { try { Add-Content -LiteralPath $log -Value ((Get-Date -Format 's') + ' ' + $m) } catch {} }
try { Wait-Process -Id $appPid -Timeout ${Math.round(p.waitSeconds ?? 120)} -ErrorAction SilentlyContinue } catch {}
if (Get-Process -Id $appPid -ErrorAction SilentlyContinue) { Log 'Quvrelo did not quit; update postponed'; exit 1 }
$code = -1
try {
  $msiArgs = @('/i', ('"' + $msi + '"'), '/qb', '/norestart', '/l*v', ('"' + $msiLog + '"'))
  $p = Start-Process -FilePath (Join-Path $env:SystemRoot 'System32\\msiexec.exe') -ArgumentList $msiArgs -Verb RunAs -Wait -PassThru
  $code = $p.ExitCode
} catch {
  Log ('elevation was refused or msiexec could not start: ' + $_.Exception.Message)
}
Log ('msiexec exit code ' + $code)
if (@(${MSI_SUCCESS.join(', ')}) -contains $code) {
  Remove-Item -LiteralPath $pending -Recurse -Force -ErrorAction SilentlyContinue
}
if ($relaunch -and (Test-Path -LiteralPath $exe)) { Start-Process -FilePath $exe }
exit $code
`;
}

/** Synchronous on purpose: it runs while the app is quitting. */
export function launchMsiInstall(plan: MsiPlan, dir: string, spawnFn: typeof spawn = spawn): string {
  const script = path.join(dir, 'quvrelo-update.ps1');
  // BOM so Windows PowerShell 5.1 reads non-ASCII paths (e.g. a user name with accents) as UTF-8
  writeFileSync(script, '\ufeff' + msiHelperScript(plan), 'utf8');
  const child = spawnFn(
    'powershell.exe',
    ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-WindowStyle', 'Hidden', '-File', script],
    { detached: true, stdio: 'ignore', windowsHide: true },
  );
  child.unref();
  return script;
}
