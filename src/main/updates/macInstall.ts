/**
 * macOS updates without an Apple Developer ID.
 *
 * Squirrel.Mac (electron-updater's MacUpdater) only installs an update whose signature
 * matches a Developer ID of the running app, so ad-hoc signed builds
 * (scripts/mac-adhoc-sign.cjs) cannot use it. Quvrelo installs these itself:
 *
 *   1. download Quvrelo-<v>-mac-<arch>.zip from latest-mac.yml, check its sha512 (files.ts)
 *   2. `ditto -x -k` it into a staging folder, check the bundle id and
 *      `codesign --verify --deep --strict` (an intact, consistently signed bundle)
 *   3. on "Restart to update" (or when the app quits) start a detached helper that
 *      waits for this process to exit, moves the old bundle aside, copies the new one in
 *      with `ditto`, re-verifies it, rolls back to the old bundle on any failure,
 *      clears the quarantine flag and relaunches with `open`
 *   4. when the bundle's folder is not writable by the user (e.g. /Applications owned by
 *      root), the swap runs through `osascript … with administrator privileges`, which
 *      shows the standard macOS password prompt; the relaunch still runs as the user.
 *
 * Script generation is pure and unit tested (the helper is also executed on Linux with
 * stub commands in tests/unit/updates-install.test.ts).
 */
import { execFile, spawn } from 'node:child_process';
import { accessSync, constants as fsc, promises as fsp, writeFileSync } from 'node:fs';
import * as path from 'node:path';

/** POSIX shell single-quote. */
export function shq(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

export interface MacSwapPlan {
  /** PID of the running Quvrelo (the helper waits for it to exit). */
  pid: number;
  /** Verified new bundle in the staging folder. */
  source: string;
  /** Installed bundle to replace, e.g. /Applications/Quvrelo.app. */
  target: string;
  /** Where the old bundle is kept until the new one is verified. */
  backup: string;
  /** Helper log file. */
  log: string;
  /** Reopen Quvrelo afterwards ("Restart to update"); false when installing on quit. */
  relaunch: boolean;
  /** Run the swap with administrator privileges (target folder not writable). */
  admin: boolean;
  /** Pending-update folder to delete after a successful install. */
  pendingDir: string;
  /** Seconds to wait for the app to exit before giving up. */
  waitSeconds?: number;
}

export function backupPathFor(target: string): string {
  return path.join(path.dirname(target), `.${path.basename(target)}.quvrelo-backup`);
}

/**
 * The privileged part: replace the bundle, verify, roll back on failure.
 * Exit codes: 0 installed, 2 staged bundle missing, 3 could not move the old bundle
 * aside (nothing changed), 4 copy failed (rolled back), 5 verification failed (rolled back).
 */
export function macSwapScript(p: MacSwapPlan): string {
  return `#!/bin/bash
# Quvrelo update: swap the app bundle (generated by macInstall.ts)
SRC=${shq(p.source)}
DST=${shq(p.target)}
BAK=${shq(p.backup)}
LOG=${shq(p.log)}
log() { printf '%s [swap] %s\\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >> "$LOG" 2>/dev/null; }
rollback() {
  log "install failed ($1); restoring the previous version"
  rm -rf "$DST"
  if [ -d "$BAK" ]; then
    mv "$BAK" "$DST" || log "ROLLBACK FAILED: previous version left at $BAK"
  fi
  exit "$2"
}
[ -d "$SRC" ] || { log "staged update missing: $SRC"; exit 2; }
OWNER=""
if [ -e "$DST" ]; then
  if [ "$(id -u)" = "0" ]; then OWNER="$(stat -f '%u:%g' "$DST" 2>/dev/null)"; fi
  rm -rf "$BAK"
  mv "$DST" "$BAK" || { log "could not move the current app aside; nothing changed"; exit 3; }
fi
ditto "$SRC" "$DST" >> "$LOG" 2>&1 || rollback "copy" 4
codesign --verify --deep --strict "$DST" >> "$LOG" 2>&1 || rollback "signature check" 5
if [ -n "$OWNER" ]; then chown -R "$OWNER" "$DST" 2>/dev/null || true; fi
xattr -dr com.apple.quarantine "$DST" 2>/dev/null || true
rm -rf "$BAK"
log "installed $DST"
exit 0
`;
}

/**
 * The unprivileged runner: wait for Quvrelo to quit, run the swap (directly or through
 * osascript for an administrator password), relaunch, tidy up.
 */
export function macRunnerScript(p: MacSwapPlan, swapScriptPath: string): string {
  const tenths = Math.round((p.waitSeconds ?? 120) * 10);
  const runSwap = p.admin
    ? `osascript -e 'on run argv' -e 'do shell script "/bin/bash " & quoted form of (item 1 of argv) with prompt "Quvrelo needs your password to install the update." with administrator privileges' -e 'end run' "$SWAP" >> "$LOG" 2>&1`
    : `/bin/bash "$SWAP"`;
  return `#!/bin/bash
# Quvrelo update runner (generated by macInstall.ts)
PID=${p.pid}
SWAP=${shq(swapScriptPath)}
DST=${shq(p.target)}
PENDING=${shq(p.pendingDir)}
LOG=${shq(p.log)}
RELAUNCH=${p.relaunch ? 1 : 0}
log() { printf '%s [runner] %s\\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >> "$LOG" 2>/dev/null; }
i=0
while kill -0 "$PID" 2>/dev/null; do
  i=$((i + 1))
  if [ "$i" -gt ${tenths} ]; then log "Quvrelo did not quit; update postponed"; exit 1; fi
  sleep 0.1
done
log "Quvrelo exited; installing"
${runSwap}
RC=$?
log "swap finished with code $RC"
if [ "$RC" = "0" ]; then rm -rf "$PENDING"; fi
if [ "$RELAUNCH" = "1" ] && [ -d "$DST" ]; then
  open "$DST" >> "$LOG" 2>&1 || log "relaunch failed"
fi
exit "$RC"
`;
}

/** Folder that holds the bundle must be writable to rename/replace it without a password. */
export function needsAdmin(target: string): boolean {
  try {
    accessSync(path.dirname(target), fsc.W_OK);
    return false;
  } catch {
    return true;
  }
}

export type Exec = (cmd: string, args: string[], opts?: { timeout?: number }) => Promise<{ code: number; stdout: string; stderr: string }>;

export const execCmd: Exec = (cmd, args, opts) =>
  new Promise((resolve) => {
    execFile(cmd, args, { timeout: opts?.timeout ?? 120_000, maxBuffer: 8 * 1024 * 1024 }, (err, stdout, stderr) => {
      const code = err ? (typeof (err as { code?: unknown }).code === 'number' ? ((err as { code: number }).code) : 1) : 0;
      resolve({ code, stdout: String(stdout ?? ''), stderr: String(stderr ?? '') || (err ? String(err.message) : '') });
    });
  });

/**
 * Unzip the downloaded update and check it before anything is replaced.
 * Returns the staged .app path.
 */
export async function stageMacUpdate(opts: {
  zip: string;
  stageDir: string;
  bundleId: string;
  version: string;
  exec?: Exec;
}): Promise<string> {
  const exec = opts.exec ?? execCmd;
  await fsp.rm(opts.stageDir, { recursive: true, force: true });
  await fsp.mkdir(opts.stageDir, { recursive: true });
  const unzip = await exec('/usr/bin/ditto', ['-x', '-k', opts.zip, opts.stageDir], { timeout: 300_000 });
  if (unzip.code !== 0) throw new Error(`Could not unpack the update: ${unzip.stderr.split('\n')[0]}`);
  const app = (await fsp.readdir(opts.stageDir)).find((n) => n.endsWith('.app'));
  if (!app) throw new Error('The update archive does not contain an app.');
  const staged = path.join(opts.stageDir, app);
  const plist = path.join(staged, 'Contents', 'Info.plist');
  const id = await exec('/usr/bin/plutil', ['-extract', 'CFBundleIdentifier', 'raw', '-o', '-', plist]);
  if (id.code !== 0 || id.stdout.trim() !== opts.bundleId) {
    throw new Error(`The update is not Quvrelo (bundle id "${id.stdout.trim() || 'unknown'}").`);
  }
  const ver = await exec('/usr/bin/plutil', ['-extract', 'CFBundleShortVersionString', 'raw', '-o', '-', plist]);
  if (ver.code === 0 && ver.stdout.trim() && ver.stdout.trim() !== opts.version) {
    throw new Error(`The update archive holds version ${ver.stdout.trim()}, expected ${opts.version}.`);
  }
  const sig = await exec('/usr/bin/codesign', ['--verify', '--deep', '--strict', staged], { timeout: 300_000 });
  if (sig.code !== 0) throw new Error(`The downloaded update failed its code signature check: ${sig.stderr.split('\n')[0]}`);
  return staged;
}

/**
 * Write both scripts next to the staged update and start the detached runner.
 * Synchronous on purpose: it runs while the app is quitting.
 */
export function launchMacSwap(plan: MacSwapPlan, dir: string, spawnFn: typeof spawn = spawn): { runner: string; swap: string } {
  const swap = path.join(dir, 'quvrelo-swap.sh');
  const runner = path.join(dir, 'quvrelo-update.sh');
  writeFileSync(swap, macSwapScript(plan), { mode: 0o755 });
  writeFileSync(runner, macRunnerScript(plan, swap), { mode: 0o755 });
  const child = spawnFn('/bin/bash', [runner], { detached: true, stdio: 'ignore' });
  child.unref();
  return { runner, swap };
}
